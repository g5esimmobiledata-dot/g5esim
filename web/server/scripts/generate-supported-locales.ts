function readLocale(code: string): LocaleData {
  const filePath = path.join(localeDir, `${code}_translations.json`);
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function maybeReadLocale(code: LocaleCode): LocaleData {
  const filePath = path.join(localeDir, `${code}_translations.json`);
  if (!fs.existsSync(filePath)) return {};
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function writeLocale(code: LocaleCode, data: LocaleData) {
  const filePath = path.join(localeDir, `${code}_translations.json`);
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
}

function protectTokens(value: string) {
  const tokens: string[] = [];
  const text = value.replace(
    /(\{\{[^}]+\}\}|\{[^}]*\}|%[sdif]|[$€£]\s?\d+(?:[.,]\d+)?|\d+(?:[.,]\d+)?[%+]?)/g,
    (match) => {
      const token = `__TOKEN_${tokens.length}__`;
      tokens.push(match);
      return token;
    },
  );

  return {
    text,
    restore: (input: string) =>
      tokens.reduce((result, tokenValue, index) => result.replaceAll(`__TOKEN_${index}__`, tokenValue), input),
  };
}

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function isTechnicalOnly(value: string) {
  const words = value.match(/[A-Za-z][A-Za-z0-9_-]*/g) || [];
  return words.length > 0 && words.every((word) => technicalTerms.has(word));
}

function translatedFromDictionary(value: string, code: LocaleCode) {
  const exact = dictionaries[code][value];
  if (exact) return exact;
  if (!/[A-Za-z]/.test(value) || isTechnicalOnly(value)) return value;

  const { text, restore } = protectTokens(value);
  let result = text;
  const combined = { ...termDictionaries[code], ...dictionaries[code] };
  const entries = Object.entries(combined).sort((a, b) => b[0].length - a[0].length);

  for (const [source, target] of entries) {
    const escaped = escapeRegExp(source).replace(/\\ /g, "\\s+");
    result = result.replace(new RegExp(`(^|[^A-Za-z])(${escaped})(?=$|[^A-Za-z])`, "gi"), `$1${target}`);
  }

  const restored = restore(result)
    .replace(/\s+([.,:;!?])/g, "$1")
    .replace(/\s{2,}/g, " ")
    .trim();

  return restored || value;
}

function completeLocale(code: LocaleCode) {
  const existing = maybeReadLocale(code);
  const preserveReviewedExisting = code === "fr" || code === "es";
  const completed: LocaleData = {};

  for (const [namespace, values] of Object.entries(sourceLocale)) {
    completed[namespace] = {};
    for (const [key, englishValue] of Object.entries(values)) {
      const existingValue = existing[namespace]?.[key];
      completed[namespace][key] =
        preserveReviewedExisting && existingValue && existingValue !== englishValue
          ? existingValue
          : translatedFromDictionary(englishValue, code);
    }
  }

  return applyAdminLanguageOverrides(code, completed);
}

for (const code of ["fr", "es", "ru", "it"] as LocaleCode[]) {
  const data = completeLocale(code);
  writeLocale(code, data);
  const total = Object.values(data).reduce((sum, namespace) => sum + Object.keys(namespace).length, 0);
  console.log(`Generated ${code}_translations.json with ${total} keys.`);
}
